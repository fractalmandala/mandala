// Emits the docs-site theme base: the DEFAULT palette's tokens at :root (light) and .dark, so
// there is no unstyled flash before the runtime theme controller injects the selected palette.
// SITE-ONLY — this does not touch the library's src/lib/styles/_tokens.sass. Regenerate with:
//   node scripts/gen-theme-base.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const themes = JSON.parse(readFileSync(`${ROOT}/src/lib/themes.json`, "utf8"));

const kebab = (k) => k.replace(/([a-z])([A-Z])/g, "$1-$2").replace(/([a-zA-Z])(\d)/g, "$1-$2").toLowerCase();
const decls = (tokens) => Object.entries(tokens).map(([k, v]) => `\t--${kebab(k)}: ${v}`).join("\n");

const d = themes.neutral;
const out = [
	"// GENERATED by scripts/gen-theme-base.mjs — the neutral palette at :root (light) and .dark.",
	"// Zero-flash defaults for the docs site. Do not hand-edit; re-run the generator. The runtime",
	"// theme controller (theme.svelte.ts) overrides these with the selected palette on <html>.",
	"",
	":root",
	decls(d.light),
	"",
	".dark",
	decls(d.dark),
	"",
].join("\n");

writeFileSync(`${ROOT}/src/lib/docs/theme-base.sass`, out);
console.log("wrote src/lib/docs/theme-base.sass");